package main

import "fmt"

func main() {
	var myString string
	// String's zero value is an empty string ("")

	fmt.Println(myString)

	myString = "This is lesson 001, Primitive Data Types"
	fmt.Println(myString)

	// ------------------------

	var myInt int
	// Integer's zero value is 0

	fmt.Println(myInt)

	myInt = 54
	fmt.Println(myInt)

	// ------------------------

	var myBoolean bool
	// Boolean's zero value is false

	fmt.Println(myBoolean)

	myBoolean = true
	fmt.Println(myBoolean)
}
