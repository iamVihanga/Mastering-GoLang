package main

import "fmt"

func main() {
	// Strings
	var myString string

	fmt.Println(myString)

	myString = "Welcome to Go!"

	fmt.Println(myString)

	// Integers
	var myInt int

	fmt.Println(myInt)

	myInt = 10

	fmt.Println(myInt)

	// Booleans
	var myBool bool

	fmt.Println(myBool)

	myBool = true

	fmt.Println(myBool)
}
